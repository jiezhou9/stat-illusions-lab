def _pp(value: float) -> str:
    if abs(value) < 1e-9:
        return "0.0 个百分点"
    return f"{value * 100:+.1f} 个百分点"


def _simpson_explanation(result: Any) -> dict[str, str]:
    mild = result.advantages["mild"]
    severe = result.advantages["severe"]
    mild_sign, severe_sign, overall_sign = result.signs
    both_better = mild_sign == 1 and severe_sign == 1
    both_worse = mild_sign == -1 and severe_sign == -1
    any_zero = mild_sign == 0 or severe_sign == 0

    if both_better:
        strata = "治疗组在轻症和重症两个分层里的康复率都更高"
    elif both_worse:
        strata = "治疗组在轻症和重症两个分层里的康复率都更低"
    elif any_zero:
        strata = "至少一个分层里，治疗组和对照组的康复率相同"
    else:
        strata = "治疗组在两个分层里的效果方向并不一致"

    see = (
        f"{strata}：轻症 {_pp(mild)}，重症 {_pp(severe)}。"
        f"合并后，治疗组整体康复率为 {result.overall_treatment:.1%}，"
        f"对照组为 {result.overall_control:.1%}。"
    )

    treatment_share = result.severe_share_treatment
    control_share = result.severe_share_control
    shares_close = abs(treatment_share - control_share) < 0.02
    if shares_close:
        share_sentence = (
            f"两组的重症占比接近（治疗组 {treatment_share:.0%}，"
            f"对照组 {control_share:.0%}）"
        )
    elif treatment_share > control_share:
        share_sentence = (
            f"治疗组的重症占比更高（{treatment_share:.0%} vs "
            f"{control_share:.0%}）"
        )
    else:
        share_sentence = (
            f"治疗组的重症占比更低（{treatment_share:.0%} vs "
            f"{control_share:.0%}）"
        )

    if shares_close:
        why = (
            f"{share_sentence}。两组的患者构成接近，合并比较中的构成差异很小；"
            "当两个分层的方向一致时，整体方向通常也与分层一致。"
        )
    else:
        why = (
            f"{share_sentence}。两组的患者构成不同，合并比较会把分层效果和"
            "构成差异混在一起。"
        )
        mild_treatment = result.table.loc[0, "treatment"]
        severe_treatment = result.table.loc[1, "treatment"]
        mild_control = result.table.loc[0, "control"]
        severe_control = result.table.loc[1, "control"]
        if severe_treatment < mild_treatment and severe_control < mild_control:
            why += (
                "当前重症的康复率低于轻症，因此重症患者更多的一组"
                "整体数字会被拉低。"
            )
        else:
            why += (
                "当两个分层的康复率不同，重症患者更多的一组整体数字"
                "会被拉向该分层的水平。"
            )

    if any_zero:
        why += (
            "\n\n至少一个分层的差值为 0。合并结果由另一层和患者构成共同决定，"
            "不能把整体差异归因于“两个分层方向相反”。"
        )
    elif overall_sign == 0:
        why += (
            "\n\n合并后的整体差值也约为 0。这不是辛普森反转，"
            "也不能据此说某一层更好或更差。"
        )
    elif result.is_reversal:
        if both_better:
            why += "\n\n这就是辛普森悖论：治疗组在每个分层里都更好，合并后却更差。"
        else:
            why += "\n\n这是反方向的辛普森悖论：治疗组在每个分层里都更差，合并后却更好。"
    elif both_better:
        why += "\n\n当前没有发生反转。把两组重症比例差距拉大，合并结果可能反向。"
    elif both_worse:
        why += (
            "\n\n当前两层都更差，合并后也更差；把两组重症比例差距拉大，"
            "可能出现反方向的反转。"
        )
    else:
        why += "\n\n分层方向不一致时，合并数字更不适合单独用来下结论。"

    return {"see": see, "why": why}


def _base_rate_explanation(result: Any) -> dict[str, str]:
    if math.isnan(result.ppv):
        see = "当前参数下没有阳性结果，阳性预测值没有定义。"
    else:
        see = (
            f"在患病率 {result.prevalence:.1%}、灵敏度 {result.sensitivity:.0%}、"
            f"特异度 {result.specificity:.0%} 时，一个阳性结果有约 "
            f"{result.ppv:.1%} 的概率对应真正患病。"
        )

    if not math.isnan(result.ppv):
        false_share = 1.0 - result.ppv
        why = (
            f"按每 {result.population:,} 人计算，方块取整后约 "
            f"{result.true_positive} 个真阳性、{result.false_positive} 个假阳性；"
            f"精确地看，阳性结果中假阳性占 {false_share:.1%}。"
        )
    else:
        why = "当前参数下没有阳性结果，无法计算阳性预测值。"

    why += (
        "\n\n方块数量按人数取整，仅用于展示；PPV 与假阳性占比使用精确概率。"
        "在小概率事件下，取整可能造成明显差异，不能用方块数量反推页面上的比例。"
    )
    return {"see": see, "why": why}


def _multiple_testing_explanation(result: Any) -> dict[str, str]:
    if result.n_significant:
        see = (
            f"在 {result.n_tests} 次完全没有真实效应的 A/A 实验中，"
            f"出现了 {result.n_significant} 个 p < {result.alpha:g} 的结果。"
        )
    else:
        see = (
            f"在 {result.n_tests} 次完全没有真实效应的 A/A 实验中，"
            f"没有出现 p < {result.alpha:g} 的结果。"
        )

    why = (
        f"单次检验的假阳性率是 {result.alpha:.1%}；{result.n_tests} 次中"
        f"至少一次显著的概率约为 {result.familywise_error:.1%}，"
        f"按期望约有 {result.expected_false_positives:.1f} 个假阳性。"
        "如果只报告显著的那几次，你报告的就是噪声，而不是发现。"
    )
    return {"see": see, "why": why}


def _regression_explanation(result: Any) -> dict[str, str]:
    see = (
        f"按第一次成绩选出前 {result.top_fraction:.0%} 的人，"
        f"他们的第一次均值为 {result.first_mean_selected:.2f}，"
        f"第二次均值为 {result.second_mean_selected:.2f}；"
        f"总体第二次均值为 {result.overall_mean:.2f}。"
    )
    if result.noise == 0:
        why = (
            "当前测量噪声为 0，两次测量完全一致，因此没有回归均值。"
            "把噪声调高，极端组的后续成绩才会向均值靠近。"
        )
    elif result.regression_amount <= 0:
        why = (
            f"当前测量噪声为 {result.noise:.1f}。理论上，按第一次成绩选拔后"
            "应出现向均值回落的趋势；但本次样本估计的平均回落为 "
            f"{result.regression_amount:.2f}，方向与理论期望相反。"
            "这是有限样本的抽样波动，不代表回归均值失效；换一个随机种子，"
            "通常会看到正的回落。"
        )
    else:
        why = (
            f"当前测量噪声为 {result.noise:.1f}。第一次高分 = 真实能力 + 好运；"
            "按第一次成绩选拔，会系统性地选到部分“运气特别好”的人。"
            "第二次测量时，好运不会继续站在同一边，成绩就会向总体均值回落。"
            f"本次选中组的平均回落为 {result.regression_amount:.2f}。"
        )
    return {"see": see, "why": why}


def _ci_explanation(result: Any) -> dict[str, str]:
    captured = int(result.intervals["captured"].sum())
    see = (
        f"重复抽样 {len(result.intervals)} 次，置信水平为 "
        f"{result.expected_coverage:.0%}；其中 {captured} 个区间"
        f"（{result.coverage:.1%}）覆盖了真实均值 {result.population_mean:g}。"
    )
    why = (
        "置信水平描述的是长期重复抽样中的覆盖率：理论上约 "
        f"{result.expected_coverage:.0%} 的区间会覆盖真值。"
        f"本次实际覆盖率为 {result.coverage:.1%}，会随随机种子和抽样次数波动。"
    )
    if abs(result.coverage - result.expected_coverage) > 0.05:
        why += " 当前偏离较大，通常来自抽样次数较少带来的随机波动。"
    return {"see": see, "why": why}


def explanation_for(key: str, result: Any) -> dict[str, str]:
    """Return explanation text with numbers from the current experiment.

    The static copy in ``EXPLANATIONS`` is the source for the general advice,
    method and formula; the ``see`` and ``why`` tabs are rebuilt from the
    result so they never contradict the controls.
    """

    if key not in EXPLANATIONS:
        raise KeyError(f"unknown experiment: {key}")

    text = dict(EXPLANATIONS[key])
    builders = {
        "simpson": _simpson_explanation,
        "base_rate": _base_rate_explanation,
        "multiple": _multiple_testing_explanation,
        "regression": _regression_explanation,
        "ci": _ci_explanation,
    }
    text.update(builders[key](result))
    return text
